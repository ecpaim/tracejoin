#!/usr/bin/env bash
# evidence-index.sh — regenerate evidence/README.md from the scenario runs on this
# HOST. Run it from anywhere after pulling one or more scenarios:
#
#   rm -rf evidence/scenario-1
#   scp -r -P 2222 ubuntu@127.0.0.1:'~/evidence/scenario-1' evidence/
#   scp -P 2222 ubuntu@127.0.0.1:~/evidence/scenario-1/curated.md docs/evidence/scenario-1.md
#   bash tools/evidence-index.sh
#
# The table is rebuilt from every evidence/scenario-*/meta.json, so re-running a
# scenario updates its row in place; all pulled scenarios stay listed side by side.
set -euo pipefail

ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
EV="$ROOT/evidence"
OUT="$EV/README.md"

command -v jq >/dev/null 2>&1 || { echo "evidence-index: jq is required" >&2; exit 1; }
[ -d "$EV" ] || { echo "evidence-index: no $EV directory yet" >&2; exit 1; }

count_src() { # ndjson source -> line count
  local f="$1" src="$2" n
  [ -s "$f" ] || { printf '0'; return 0; }
  n=$(jq -r --arg s "$src" 'select(.source == $s) | 1' "$f" 2>/dev/null | wc -l) || n=0
  printf '%s' "${n// /}"
}

shopt -s nullglob
metas=("$EV"/scenario-*/meta.json)
shopt -u nullglob
if [ "${#metas[@]}" -gt 1 ]; then
  mapfile -t metas < <(printf '%s\n' "${metas[@]}" | sort -V)
fi

{
  echo "# Evidence index"
  echo
  echo "Auto-generated by \`tools/evidence-index.sh\` from \`evidence/scenario-*/meta.json\`."
  echo "Raw evidence is gitignored; curated write-ups are tracked under \`docs/evidence/\`."
  echo
  if [ "${#metas[@]}" -eq 0 ]; then
    echo "_No scenarios pulled yet._"
  else
    echo "| scenario | technique | window (UTC) | collected | auditd | falco | zeek | suricata | curated |"
    echo "|---|---|---|---|---|---|---|---|---|"
    for m in "${metas[@]}"; do
      d="$(dirname "$m")"; ev="$d/events.ndjson"
      jq -e . "$m" >/dev/null 2>&1 || { echo "evidence-index: skipping invalid $m" >&2; continue; }
      id="$(jq -r '.scenario // "?"' "$m")"
      tech="$(jq -r '.technique // ""' "$m")"
      w0="$(jq -r '.window.t0 // ""' "$m")"
      w1="$(jq -r '.window.t1 // ""' "$m")"
      col="$(jq -r '.collected_at // ""' "$m")"
      if [ -f "$ROOT/docs/evidence/scenario-$id.md" ]; then
        curated="[scenario-$id.md](../docs/evidence/scenario-$id.md)"
      else
        curated="—"
      fi
      printf '| %s | %s | %s → %s | %s | %s | %s | %s | %s | %s |\n' \
        "$id" "$tech" "$w0" "$w1" "$col" \
        "$(count_src "$ev" auditd)" "$(count_src "$ev" falco)" \
        "$(count_src "$ev" zeek)" "$(count_src "$ev" suricata)" \
        "$curated"
    done
  fi
} > "$OUT"

echo "wrote $OUT"
